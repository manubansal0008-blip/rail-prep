// Builds src/sitemap-catalog.js: the list of Rail Prep pages the doubt chat may link to.
//   node scripts/build-catalog.mjs [SITE_DIR]     (default: the site repo this worker/ folder sits in, i.e. ..)
// Re-run (and redeploy) only when notes are added or renamed. Daily news needs no re-run: the chat links to news.html.
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SITE = path.resolve(process.argv[2] || path.join(here, "..", ".."));
const OUT = path.join(here, "..", "src", "sitemap-catalog.js");
const ctx = { RRB: {} }; vm.createContext(ctx);
const load = (p) => vm.runInContext(fs.readFileSync(path.join(SITE, p), "utf8"), ctx, { filename: p });
load("data/topics.js"); load("data/notes/index.js");
const R = ctx.RRB, TOP = Object.fromEntries(R.TOPICS.topics.map((t) => [t.k, t]));
const EXTRA = Object.fromEntries((R.NOTES_EXTRA || []).map((t) => [t.k, t]));
const clip = (s, n) => { s = String(s).replace(/\s+/g, " ").trim(); return s.length <= n ? s : s.slice(0, n).replace(/\s+\S*$/, ""); };

const notes = [];
for (const k of R.NOTES_READY) {
  const meta = TOP[k] || EXTRA[k];
  if (!meta) throw new Error("No title for note " + k);
  if (!fs.existsSync(path.join(SITE, "notes", k + ".html"))) throw new Error("Missing static page notes/" + k + ".html (run build_static.py)");
  let kw = [];
  const f = path.join(SITE, "data/notes", k + ".js");
  if (fs.existsSync(f)) {
    ctx.RRB.noteLoaded = (n) => { ctx.__n = n; }; ctx.__n = null;
    vm.runInContext(fs.readFileSync(f, "utf8"), ctx, { filename: f });
    const n = ctx.__n || {};
    kw = ((n.en && n.en.concepts) || []).map((c) => clip(c.h || "", 40)).filter(Boolean).slice(0, 4);
  }
  const practice = TOP[k] ? k : meta.p && TOP[meta.p] ? meta.p : "";
  notes.push({ slug: k, s: meta.s, en: meta.en, hi: meta.hi, kw: kw.join("; "), practice });
}
const pages = [
  { path: "", en: "Rail Prep home", hi: "होम", kw: "start, exam dates, question of the day" },
  { path: "mock.html", en: "Full mock tests (NTPC UG and Group D, exam-like CBT)", hi: "मॉक टेस्ट", kw: "full test, timed practice, exam-like" },
  { path: "practice.html", en: "Topic-wise practice questions", hi: "टॉपिक के हिसाब से प्रैक्टिस", kw: "practice, drill, chapter-wise" },
  { path: "papers.html", en: "RRB past papers with answer keys", hi: "पुराने पेपर", kw: "previous year papers, PYQ, answer key" },
  { path: "notes.html", en: "All revision notes", hi: "सभी नोट्स", kw: "notes list, syllabus" },
  { path: "news.html", en: "Daily current affairs 2026 (today's 5 news)", hi: "आज की ख़बरें", kw: "current affairs, latest news, daily GK" },
  { path: "news/index.html", en: "Current affairs: all days", hi: "सभी दिन की ख़बरें", kw: "past days news archive" },
  { path: "progress.html", en: "Your progress and weak topics", hi: "आपकी प्रगति", kw: "score history, weak topics" }
];
const src = `// GENERATED by scripts/build-catalog.mjs from the site data. Do not edit by hand; re-run the script instead.
// Pages the doubt chat may link to. Paths are relative to BASE. Notes: BASE + "notes/" + slug + ".html";
// practice: BASE + "practice.html?topic=" + practice.
export const BASE = "https://manubansal0008-blip.github.io/rail-prep/";
export const PAGES = ${JSON.stringify(pages, null, 0).replace(/\},\{/g, "},\n  {")};
export const NOTES = ${JSON.stringify(notes, null, 0).replace(/\},\{/g, "},\n  {")};
`;
fs.writeFileSync(OUT, src);
console.log("Wrote", path.relative(process.cwd(), OUT), "-", pages.length, "pages,", notes.length, "notes");
